import asyncio, sys
from playwright.async_api import async_playwright
SP = sys.argv[1]
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
        ctx = await b.new_context(viewport={'width':1360,'height':900})
        pg = await ctx.new_page()
        errs = []
        pg.on('pageerror', lambda e: errs.append('pageerror: %s' % e))
        pg.on('console', lambda m: errs.append('console.%s: %s' % (m.type, m.text)) if m.type == 'error' else None)
        await pg.goto('file:///home/claude/ashita-gear-studio/standalone/index.html')
        await pg.wait_for_selector('.doll')
        await pg.click('button.slot:has-text("Head")')
        await pg.fill('[role=combobox]', 'optical')
        await pg.keyboard.press("ArrowDown"); await pg.keyboard.press("ArrowUp"); await pg.keyboard.press("Enter")
        assert 'Optical Hat' in await pg.inner_text('button.slot:has-text("Head")')
        await pg.fill('[role=combobox]', 'Fancy Cap +1'); await pg.keyboard.press('Enter')  # only row is the typed one
        await pg.fill('textarea[placeholder="Example: DEX+5"]', 'DEX+5')
        await pg.select_option('.row-item select >> nth=0', 'B')
        await pg.click('text=Game data…')
        async with pg.expect_file_chooser() as fc:
            await pg.click('text=Choose game data files…')
        await (await fc.value).set_files([SP + '/items.lua', SP + '/spells.lua'])
        await pg.wait_for_selector('.summary')
        print(await pg.inner_text('.summary'))
        await pg.click('.dialog >> text=Done')
        await pg.click('button.slot:has-text("Head")')
        print('placeholder:', await pg.get_attribute('[role=combobox]', 'placeholder'))
        await pg.fill('[role=combobox]', 'cap 1')
        await pg.wait_for_selector('.result')
        print('results', await pg.eval_on_selector_all('.result', 'e=>e.length'))
        await pg.fill('input[type=number][placeholder=Any] >> nth=0', '10')
        lv = await pg.eval_on_selector_all('.result .lv', 'e=>e.map(x=>parseInt(x.textContent.replace("Lv ","")))')
        assert all(x <= 10 for x in lv), lv
        await pg.fill('[role=combobox]', '')
        assert 'Not in game data' in await pg.inner_text('.doll')
        await pg.screenshot(path='/tmp/final-sets.png')
        await pg.click('[role=tab]:has-text("Rules")')
        await pg.click('[role=tab]:has-text("Midcast")')
        before0 = await pg.eval_on_selector_all('.rule', 'e=>e.length')
        await pg.click('text=+ Add a rule')
        await pg.click('.rule >> nth=-1 >> text=+ Condition')
        await pg.click('.rule >> nth=-1 >> text=+ Group')
        await pg.screenshot(path='/tmp/final-rules.png')
        before = await pg.eval_on_selector_all('.rule', 'e=>e.length')
        await pg.click('button[aria-label=Undo]'); await pg.click('button[aria-label=Undo]'); await pg.click('button[aria-label=Undo]')
        mid = await pg.eval_on_selector_all('.rule', 'e=>e.length')
        for _ in range(3): await pg.click('button[aria-label=Redo]')
        after = await pg.eval_on_selector_all('.rule', 'e=>e.length')
        print('rules start/before/undo/redo', before0, before, mid, after)
        assert mid == before0 and after == before
        await pg.click('[role=tab]:has-text("Lua")')
        lua = await pg.inner_text('pre.lua')
        assert "Name = 'Fancy Cap +1'" in lua and "AugPath = 'B'" in lua, lua[:700]
        await pg.click('text=Import Lua')
        await pg.fill('textarea[aria-label="Lua to import"]', "local profile = {};\nlocal sets = { Idle = { Head = 'X' } };\nprofile.Sets = sets;\nprofile.HandleDefault = function()\n  local player = gData.GetPlayer();\n  if (player.Status == 'Engaged') then gFunc.EquipSet(sets.Idle); end\nend\nreturn profile;")
        await pg.click('.dialog footer >> text=Import')
        await pg.wait_for_selector('text=Import report')
        await pg.click('text=Import Lua')
        await pg.fill('textarea[aria-label="Lua to import"]', "local x = 'oops")
        await pg.click('.dialog footer >> text=Import')
        assert 'valid Lua' in await pg.inner_text('.err-text')
        await pg.keyboard.press('Escape')
        await pg.wait_for_timeout(900)
        await pg.reload(); await pg.wait_for_selector('.doll')
        n = await pg.eval_on_selector_all('select[aria-label=Profile] option', 'e=>e.length')
        assert n == 2, n
        await pg.click('button.slot:has-text("Head")')
        ph = await pg.get_attribute('[role=combobox]', 'placeholder')
        assert ph.startswith('Search') and 'sample' not in ph, ph
        print('persisted: profiles', n, '|', ph)
        await pg.set_viewport_size({'width':390,'height':800})
        for tab in ['Gear Sets','Rules','Profile','Lua']:
            await pg.click('[role=tab]:has-text("%s")' % tab)
            sw = await pg.evaluate('document.documentElement.scrollWidth')
            print('phone', tab, sw)
            assert sw <= 392, (tab, sw)
        await pg.screenshot(path='/tmp/final-phone.png')
        await b.close()
    print('ERRORS:', errs if errs else 'none')
asyncio.run(main())
